//! The CSS Color Module Level 4 named colors, and `transparent`.

use super::Color;

/// Defines each name's constant on [`Color`] and the table [`lookup`] reads, from one list, so the
/// two can't diverge.
macro_rules! names {
  ($($constant:ident $name:literal ($r:literal, $g:literal, $b:literal, $a:literal),)*) => {
    impl Color {
      $(
        #[doc = concat!("`", $name, "`: `rgba(", $r, ", ", $g, ", ", $b, ", ", $a, ")`.")]
        pub const $constant: Color = Color::rgba($r, $g, $b, $a);
      )*
    }

    /// Every name, lowercase, with its color.
    pub(super) const NAMES: &[(&str, Color)] = &[$(($name, Color::$constant)),*];
  };
}

