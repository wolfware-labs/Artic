/// The color named `name`, ignoring ASCII case.
pub(super) fn lookup(name: &str) -> Option<Color> {
  NAMES
    .iter()
    .find(|(known, _)| known.eq_ignore_ascii_case(name))
    .map(|(_, color)| *color)
}
